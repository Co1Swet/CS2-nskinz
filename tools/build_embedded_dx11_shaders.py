"""Regenerate checked-in ImGui DXBC headers (developer-only Windows SDK tool)."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fxc", required=True, type=Path)
    parser.add_argument("--check", action="store_true", help="Verify without modifying headers")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    shaders = root / "src/UI/Shaders"
    for name, profile in (("Vertex", "vs_4_0"), ("Pixel", "ps_4_0")):
        source = shaders / f"ImGui{name}.hlsl"
        with tempfile.TemporaryDirectory(prefix="nskinz-shader-") as temporary:
            bytecode = Path(temporary) / "shader.cso"
            # Match the old D3DCompile(..., flags=0) defaults. No debug data or
            # absolute build paths are needed in the checked-in DXBC.
            subprocess.run(
                [str(args.fxc), "/nologo", "/T", profile, "/E", "main",
                 "/Fo", str(bytecode), str(source)], check=True,
            )
            data = bytecode.read_bytes()
        if not data.startswith(b"DXBC"):
            raise RuntimeError(f"{source.name}: FXC did not produce DXBC")
        digest = hashlib.sha256(source.read_bytes().replace(b"\r\n", b"\n")).hexdigest()
        lines = [
            "// Generated by tools/build_embedded_dx11_shaders.py; do not edit.",
            "// Derived from Dear ImGui (MIT): https://github.com/ocornut/imgui/blob/master/LICENSE.txt",
            f"// Source SHA256 (LF): {digest}",
            "#pragma once", "",
            f"inline constexpr unsigned char kImGui{name}Shader[] = {{",
        ]
        for offset in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset+16]) + ",")
        text = "\n".join(lines + ["};", ""])
        output = shaders / f"ImGui{name}.generated.hpp"
        if args.check:
            if output.read_text(encoding="utf-8") != text:
                raise RuntimeError(f"Stale embedded shader: {output}")
        else:
            output.write_text(text, encoding="utf-8", newline="\n")
        print(f"{output.name}: {len(data)} bytes, source {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
